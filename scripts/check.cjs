const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const files=['public/index.html','public/style.css','public/app.js','public/assets/neural-origin-v2.png','api/health.js'];
for(const file of files)assert.ok(fs.statSync(path.join(root,file)).size>0,file);
new vm.Script(fs.readFileSync(path.join(root,'public/app.js'),'utf8'));
new vm.Script(fs.readFileSync(path.join(root,'api/health.js'),'utf8'));
const html=fs.readFileSync(path.join(root,'public/index.html'),'utf8');
for(const label of ['Comenzar','Toda decisión','id="skip"','id="replay"'])assert.ok(html.includes(label));
const config=JSON.parse(fs.readFileSync(path.join(root,'vercel.json'),'utf8'));
assert.equal(config.outputDirectory,'public');
console.log('PASS: required files, JavaScript syntax, opening controls and Vercel output.');
